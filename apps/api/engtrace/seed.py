def _artifact(
    id: str,
    kind: ArtifactType,
    title: str,
    content: str,
    source: str,
    owner: str,
    criticality: Criticality = Criticality.HIGH,
    tags: list[str] | None = None,
    version: int = 1,
    status: str = "active",
) -> Artifact:
    return Artifact(
        id=id,
        type=kind,
        title=title,
        content=content,
        source=source,
        owner=owner,
        criticality=criticality,
        tags=tags or [],
        version=version,
        status=status,
        updated_at=SEED_TIME,
    )


